export function seededRandom(seed: number) {
  let s = seed % 2147483647;
  if (s <= 0) s += 2147483646;
  return function () {
    s = (s * 16807) % 2147483647;
    return (s - 1) / 2147483646;
  };
}

export function buildProperties() {
  const rand = seededRandom(918273);
  const props = [];
  let id = 1;
  DISTRICT_LIST.forEach((d) => {
    // Generate active listings across categories for each district
    PROPERTY_CATEGORIES.forEach((cat) => {
      const isPopular = ["1bed", "2bed", "3bed", "4bed", "duplex", "mini-flat", "self-contained", "studio"].includes(cat.key);
      const listingsForCategory = isPopular ? (rand() > 0.4 ? 2 : 1) : (rand() > 0.6 ? 2 : 1);
      for (let i = 0; i < listingsForCategory; i++) {
        const type = cat.label;
        const agent = AGENT_LIST[Math.floor(rand() * AGENT_LIST.length)];
        const [minBed, maxBed] = cat.bedrooms;
        const bedrooms = minBed + Math.floor(rand() * (maxBed - minBed + 1));
        const bathrooms = Math.max(1, bedrooms - Math.floor(rand() * 2));
        const parking = Math.floor(rand() * 4);
        const basePrice = 1200000 + Math.floor(rand() * 7) * 850000;
        const furnished = rand() > 0.5;
        const serviced = rand() > 0.55;
        const petFriendly = rand() > 0.7;
        const verified = rand() > 0.25;
        const premium = rand() > 0.72;
        const isNew = rand() > 0.65;
        const status = premium && isNew ? "Featured Listing" : STATUSES[Math.floor(rand() * STATUSES.length)];
        const popularity = Math.floor(rand() * 500);
        const daysAgo = Math.floor(rand() * 120);
        const reviewCount = 2 + Math.floor(rand() * 3);
        props.push({
          id: id++,
          title: `${type} in ${d.name}`,
          districtKey: d.key,
          district: d.name,
          type,
          categoryKey: cat.key,
          price: basePrice,
          bedrooms,
          bathrooms,
          parking,
          furnished,
          serviced,
          petFriendly,
          verified,
          premium,
          isNew,
          status,
          popularity,
          daysAgo,
          agentId: agent.id,
          description: `A ${bedrooms}-bedroom ${type.toLowerCase()} in ${d.name}, ${furnished ? "fully furnished, " : ""}${serviced ? "serviced, " : ""}with ${parking} parking space${parking === 1 ? "" : "s"}. Close to major roads and everyday conveniences in the district.`,
          reviewCount,
        });
      }
    });
  });
  return props;
}

